/* Firewall: block by IP / range / subnet / country, allowlist, auto-ban from the Nginx access log, and a traffic report.
   Layers: (1) Node guard for app pages, (2) generated Nginx allow/deny file that covers the static site too. */
const fs = require("fs"), path = require("path"), express = require("express");
const store = require("./store"), UI = require("./ui"), ip = require("./ipmath");
let maxmind = null; try { maxmind = require("maxmind"); } catch { /* optional: country blocking needs it */ }

module.exports = ({ page, h1, esc, hidden, verifyCsrf }) => {
  const FILE = "firewall.json";
  const NGINX_FILE = process.env.FIREWALL_NGINX_FILE || path.join(__dirname, "data", "nginx-firewall.conf");
  const LOG = process.env.NGINX_ACCESS_LOG || "/var/log/nginx/access.log";
  const cfg = Object.assign({ allow: [], block: [], countries: [], bans: [], auto: { on: true, limit: 40, windowMin: 10, banHours: 6 } }, store.read(FILE, {}));
  let rules = { allow: [], block: [], bans: [] }, geo = null, blocked = [], blockedCount = 0;
  const plain = a => String(a).replace(/^::ffff:/i, "");

  const compile = () => {
    cfg.bans = cfg.bans.filter(b => b.until > Date.now());
    const p = l => l.map(r => ip.parseRule(r.text || r.ip)).filter(r => r && r.kind !== "country");
    rules = { allow: p(cfg.allow), block: p(cfg.block), bans: p(cfg.bans) };
  };
  const writeNginx = () => {
    const lines = ["# Generated by the vibepress firewall. Do not edit by hand."];
    rules.allow.forEach(r => ip.toCidrs(r).forEach(c => lines.push("allow " + c + ";")));
    rules.block.concat(rules.bans).forEach(r => ip.toCidrs(r).forEach(c => lines.push("deny " + c + ";")));
    const txt = lines.join("\n") + "\n";
    try { if (fs.existsSync(NGINX_FILE) && fs.readFileSync(NGINX_FILE, "utf8") === txt) return; fs.writeFileSync(NGINX_FILE, txt, { mode: 0o644 }); }
    catch (e) { console.error("firewall: cannot write " + NGINX_FILE + ": " + e.message); }
  };
  const save = () => { compile(); store.write(FILE, cfg); writeNginx(); };

  const hit = (list, b) => list.some(r => ip.contains(r, b));
  const countryOf = a => { try { const c = geo && geo.get(plain(a)); return (c && c.country && c.country.iso_code) || ""; } catch { return ""; } };
  const check = addr => {
    const b = ip.toBig(addr); if (!b) return null;
    if (hit(rules.allow, b)) return null;
    if (hit(rules.bans, b)) return "auto-ban";
    if (hit(rules.block, b)) return "blocked rule";
    if (geo && cfg.countries.length) { const c = countryOf(addr); if (c && cfg.countries.some(x => x.code === c)) return "country " + c; }
    return null;
  };
  const guard = (req, res, next) => {
    const why = check(req.ip); if (!why) return next();
    blockedCount++; blocked.unshift({ t: new Date().toISOString(), ip: req.ip, path: req.originalUrl.slice(0, 100), why }); if (blocked.length > 30) blocked.pop();
    res.status(403).type("text/plain").send("Access denied");
  };

  /* ---- Nginx access log: auto-ban and report ---- */
  const LINE = /^(\S+) \S+ \S+ \[([^\]]+)\] "(\S+) (\S+)[^"]*" (\d{3}) \S+ "[^"]*" "([^"]*)"/;
  const MON = { Jan: 0, Feb: 1, Mar: 2, Apr: 3, May: 4, Jun: 5, Jul: 6, Aug: 7, Sep: 8, Oct: 9, Nov: 10, Dec: 11 };
  const parseTime = s => { const m = /^(\d+)\/(\w+)\/(\d+):(\d+):(\d+):(\d+) ([+-])(\d\d)(\d\d)$/.exec(s); if (!m) return 0;
    return Date.UTC(+m[3], MON[m[2]], +m[1], +m[4], +m[5], +m[6]) - (m[7] === "-" ? -1 : 1) * (+m[8] * 60 + +m[9]) * 60000; };
  const readLog = maxBytes => {
    let fd, buf;
    try { fd = fs.openSync(LOG, "r"); const size = fs.fstatSync(fd).size, n = Math.min(size, maxBytes); buf = Buffer.alloc(n); fs.readSync(fd, buf, 0, n, size - n); }
    catch { return null; } finally { if (fd !== undefined) try { fs.closeSync(fd); } catch {} }
    const out = [];
    for (const line of buf.toString("utf8").split("\n")) { const m = LINE.exec(line); if (m) out.push({ ip: m[1], t: parseTime(m[2]), path: m[4], status: +m[5] }); }
    return out;
  };
  const tick = () => {
    const now = Date.now(), before = cfg.bans.length; let changed = false;
    compile(); if (cfg.bans.length !== before) changed = true;
    if (cfg.auto.on) {
      const rows = readLog(1500000);
      if (rows) {
        const from = now - cfg.auto.windowMin * 60000, cnt = {};
        rows.forEach(r => { if (r.t >= from && r.status >= 400 && r.status < 500 && r.status !== 403) cnt[r.ip] = (cnt[r.ip] || 0) + 1; });
        for (const [a, n] of Object.entries(cnt)) {
          const b = ip.toBig(a);
          if (n < cfg.auto.limit || !b || ip.isPrivate(a) || hit(rules.allow, b) || hit(rules.bans, b) || hit(rules.block, b)) continue;
          cfg.bans.push({ ip: plain(a), until: now + cfg.auto.banHours * 3600000, reason: n + " errors in " + cfg.auto.windowMin + " min", added: new Date().toISOString() });
          compile(); changed = true;
        }
      }
    }
    if (changed) save();
  };
  const report = () => {
    const rows = readLog(2000000); if (!rows) return null;
    const ips = {}, p404 = {}, cls = {};
    rows.forEach(r => { const o = ips[r.ip] = ips[r.ip] || { n: 0, e: 0 }; o.n++; if (r.status >= 400 && r.status < 500) o.e++;
      if (r.status === 404) { const p = r.path.split("?")[0].slice(0, 80); p404[p] = (p404[p] || 0) + 1; }
      const c = Math.floor(r.status / 100) + "xx"; cls[c] = (cls[c] || 0) + 1; });
    const top = o => Object.entries(o).sort((a, b) => (b[1].n !== undefined ? b[1].n - a[1].n : b[1] - a[1]));
    return { total: rows.length, since: rows.length ? rows[0].t : 0, cls, uniq: Object.keys(ips).length, top: top(ips).slice(0, 15), p404: top(p404).slice(0, 10) };
  };

  /* ---- admin page ---- */
  const admin = express.Router();
  const date = t => new Date(t).toLocaleString("en-US", { dateStyle: "medium", timeStyle: "short" });
  const form = (req, action, fields, label, cls = "") => `<form class="inline" method="post" action="/admin/firewall/${action}">${hidden(req)}${Object.entries(fields).map(([k, v]) => `<input type="hidden" name="${k}" value="${esc(v)}">`).join("")}<button class="${cls}">${label}</button></form>`;
  const view = (req, msg) => {
    const rep = report(), bar = (list, name) => list.map((r, i) => `<div class="row"><strong>${esc(r.text || r.code)}</strong><span class="meta">${esc(r.note || "")}</span>${form(req, "remove", { list: name, i }, "Remove", "danger")}</div>`).join("") || '<p class="meta">None.</p>';
    return page("Firewall", `${h1("Firewall")}<p><a href="/admin/">&larr; Dashboard</a></p>${msg ? `<p class="err">${esc(msg)}</p>` : ""}
<p class="meta">Your address: <strong>${esc(plain(req.ip))}</strong> ${form(req, "allowme", {}, "Always allow my address")} &nbsp; GeoIP (country blocking): <strong>${geo ? "active" : "not set up"}</strong></p>
<form class="wide" method="post" action="/admin/firewall/add">${hidden(req)}
<label>IP, range, subnet or country code (203.0.113.5 | 203.0.113.5-203.0.113.90 | 203.0.113.0/24 | CN)<input name="text" required maxlength="100"></label>
<label>Note (optional)<input name="note" maxlength="100"></label>
<label>Action<select name="list"><option value="block">Block</option><option value="allow">Always allow</option></select></label><button>Add rule</button></form>
<h3 class="cat">Blocked</h3>${bar(cfg.block, "block")}
<h3 class="cat">Blocked countries</h3>${bar(cfg.countries, "countries")}${!geo && cfg.countries.length ? '<p class="note">Country rules are saved but inactive until a GeoIP database is set up. They only cover the app pages (blog, forms, admin), not static pages.</p>' : ""}
<h3 class="cat">Always allowed</h3>${bar(cfg.allow, "allow")}
<h3 class="cat">Automatic bans</h3>${cfg.bans.map((b, i) => `<div class="row"><strong>${esc(b.ip)}</strong><span class="meta">${esc(b.reason)}, until ${date(b.until)}</span>${form(req, "perm", { i }, "Make permanent")}${form(req, "remove", { list: "bans", i }, "Unban", "danger")}</div>`).join("") || '<p class="meta">None right now.</p>'}
<form class="wide" method="post" action="/admin/firewall/settings">${hidden(req)}<p class="meta">Auto-ban: an address is banned when it causes at least</p>
<label>Errors (4xx) <input name="limit" type="number" min="5" max="1000" value="${cfg.auto.limit}"></label><label>within minutes <input name="windowMin" type="number" min="1" max="120" value="${cfg.auto.windowMin}"></label><label>Ban hours <input name="banHours" type="number" min="1" max="720" value="${cfg.auto.banHours}"></label>
<label><select name="on"><option value="1"${cfg.auto.on ? " selected" : ""}>Auto-ban on</option><option value="0"${cfg.auto.on ? "" : " selected"}>Auto-ban off</option></select></label><button>Save settings</button></form>
<h3 class="cat">Traffic report</h3>${rep ? `<p class="meta">${rep.total} requests since ${date(rep.since)} from ${rep.uniq} addresses. Status groups: ${Object.entries(rep.cls).map(([k, v]) => k + " " + v).join(", ")}.</p>
<p><strong>Top addresses</strong></p>${rep.top.map(([a, o]) => `<div class="row"><strong>${esc(a)}</strong><span class="meta">${o.n} requests, ${o.e} errors${countryOf(a) ? ", " + countryOf(a) : ""}</span>${ip.isPrivate(a) ? "" : form(req, "add", { text: a, list: "block", note: "from report" }, "Block", "danger")}</div>`).join("")}
<p><strong>Most requested missing pages (often scanners)</strong></p>${rep.p404.map(([p, n]) => `<div class="row"><code>${esc(p)}</code><span class="meta">${n}</span></div>`).join("") || '<p class="meta">None.</p>'}`
      : `<p class="note">The Nginx access log could not be read. Run <code>sudo usermod -aG adm deploy</code>, log out and back in, then restart the app (see the cheat sheet).</p>`}
<h3 class="cat">Recently blocked at the app (${blockedCount} since restart)</h3>${blocked.map(b => `<div class="row"><strong>${esc(b.ip)}</strong><span class="meta">${esc(b.why)} | ${esc(b.path)} | ${date(b.t)}</span></div>`).join("") || '<p class="meta">None yet.</p>'}`, { head: UI });
  };
  const fail = (req, res, m) => res.status(400).send(view(req, m));

  admin.get("/", (req, res) => res.send(view(req)));
  admin.post("/add", verifyCsrf, (req, res) => {
    const r = ip.parseRule(req.body.text), list = req.body.list === "allow" ? "allow" : "block", note = String(req.body.note || "").slice(0, 100), added = new Date().toISOString();
    if (!r) return fail(req, res, "That is not a valid IP, range, subnet or country code.");
    if (r.kind === "country") {
      if (list === "allow") return fail(req, res, "Country rules can only block.");
      if (!cfg.countries.some(c => c.code === r.code)) cfg.countries.push({ code: r.code, note, added });
    } else {
      const me = ip.toBig(req.ip);
      if (list === "block" && me && ip.contains(r, me)) return fail(req, res, "That rule would block your own address, so it was not added.");
      if (list === "block" && ip.isPrivate(ip.toStr(r.lo, r.v))) return fail(req, res, "Private and local addresses cannot be blocked.");
      if (!cfg[list].some(x => x.text === r.text)) cfg[list].push({ text: r.text, note, added });
    }
    save(); res.redirect("/admin/firewall/");
  });
  admin.post("/allowme", verifyCsrf, (req, res) => {
    const r = ip.parseRule(plain(req.ip)); if (r && !cfg.allow.some(x => x.text === r.text)) cfg.allow.push({ text: r.text, note: "my address", added: new Date().toISOString() });
    save(); res.redirect("/admin/firewall/");
  });
  admin.post("/remove", verifyCsrf, (req, res) => {
    const l = ["block", "allow", "countries", "bans"].includes(req.body.list) ? req.body.list : null, i = parseInt(req.body.i, 10);
    if (l && i >= 0 && i < cfg[l].length) cfg[l].splice(i, 1);
    save(); res.redirect("/admin/firewall/");
  });
  admin.post("/perm", verifyCsrf, (req, res) => {
    const i = parseInt(req.body.i, 10), b = cfg.bans[i];
    if (b) { cfg.block.push({ text: ip.parseRule(b.ip).text, note: "was auto-ban: " + b.reason, added: new Date().toISOString() }); cfg.bans.splice(i, 1); }
    save(); res.redirect("/admin/firewall/");
  });
  admin.post("/settings", verifyCsrf, (req, res) => {
    const n = (v, lo, hi, d) => { v = parseInt(v, 10); return v >= lo && v <= hi ? v : d; };
    cfg.auto = { on: req.body.on === "1", limit: n(req.body.limit, 5, 1000, 40), windowMin: n(req.body.windowMin, 1, 120, 10), banHours: n(req.body.banHours, 1, 720, 6) };
    save(); res.redirect("/admin/firewall/");
  });

  const start = () => {
    compile(); writeNginx(); setInterval(tick, 60000).unref();
    if (maxmind && process.env.GEOIP_DB) maxmind.open(process.env.GEOIP_DB).then(g => { geo = g; console.log("firewall: GeoIP database loaded"); })
      .catch(e => console.error("firewall: GeoIP database failed: " + e.message));
  };
  return { guard, admin, start, country: countryOf };
};
